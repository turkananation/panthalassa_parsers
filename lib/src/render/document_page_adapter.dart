/// Renders a [DocumentIr] (semantic content) together with an optional
/// [VisualDocument] (faithful display-list pages) into a beautiful, responsive,
/// self-contained HTML page.
///
/// The output is framework-free and web-safe: all CSS and JavaScript are
/// embedded inline so the page opens from `file://` without a server. It
/// supports light/dark/system themes, a generated table of contents, copyable
/// code blocks and document id, print styles, and a responsive visual page
/// gallery.
final class DocumentPageAdapter {
  const DocumentPageAdapter();

  /// Renders [ir] with an optional [visual] projection into a single HTML
  /// document.
  ///
  /// [options] are forwarded to the semantic [HtmlDocumentRenderer].
  String render({
    required DocumentIr ir,
    VisualDocument? visual,
    RenderOptions options = const RenderOptions(),
  }) {
    final semantic = const HtmlDocumentRenderer().render(
      ir,
      options: options,
    );
    final svg = visual == null || visual.isEmpty
        ? ''
        : const SvgVisualRenderer().render(visual);
    final title = _pageTitle(ir);
    final shortId = ir.contentId != null && ir.contentId!.length > 16
        ? ir.contentId!.substring(0, 16)
        : (ir.contentId ?? '-');
    return '''
<!doctype html>
<html lang="en" data-theme="system">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="panthalassa">
<title>${_escapeHtml(title)}</title>
<style>$_pageStyle</style>
</head>
<body>
<a class="skip-link" href="#content">Skip to content</a>
<header class="doc-header">
  <div class="header-inner">
    <div class="brand">panthalassa</div>
    <div class="panthalassa-title">${_escapeHtml(title)}</div>
    <div class="doc-meta">
      <span class="format-chip">Format: ${_escapeHtml(ir.sourceFormat.name)}</span>
      <span class="doc-id-badge" title="${_escapeHtml(ir.contentId ?? '-')}">
        <span class="doc-id-label">id</span>
        <span class="doc-id-value">${_escapeHtml(shortId)}${ir.contentId != null && ir.contentId!.length > 16 ? '…' : ''}</span>
      </span>
    </div>
    <div class="header-actions">
      <button type="button" class="icon-btn" id="theme-toggle" aria-label="Toggle theme" title="Toggle theme">
        <span class="theme-icon">🌓</span>
      </button>
      <button type="button" class="action-btn" id="copy-id" aria-label="Copy document id" title="Copy document id">
        <span class="copy-icon">📋</span> Copy id
      </button>
      <button type="button" class="action-btn" id="print-btn" aria-label="Print document" title="Print document">
        <span class="print-icon">🖨️</span> Print
      </button>
    </div>
  </div>
</header>
${_tocShell()}
<main id="content" class="doc-body" tabindex="-1">
  ${_metadataCard(ir.metadata, options.includeMetadata, shortId)}
  $semantic
  ${_visualBlock(svg, visual)}
</main>
<footer class="doc-footer">
  <div class="footer-inner">
    <span class="footer-text">${_escapeHtml(ir.sourceFormat.name)} · documentId ${_escapeHtml(ir.contentId ?? '-')}</span>
    <span class="footer-divider">·</span>
    <span class="footer-text">Generated by panthalassa</span>
  </div>
</footer>
<button type="button" class="back-to-top" id="back-to-top" aria-label="Back to top" title="Back to top">
  <span class="btt-icon">↑</span>
</button>
<script>$_pageScript</script>
</body>
</html>
''';
  }

  String _pageTitle(DocumentIr ir) {
    for (final block in ir.body) {
      if (block is HeadingBlock && block.text.isNotEmpty) {
        return block.text.map((i) {
          if (i is TextRun) return i.text;
          return '';
        }).join().trimRight();
      }
    }
    return 'panthalassa document';
  }

  String _tocShell() {
    return '''
<nav class="doc-toc" aria-label="Table of contents">
  <div class="toc-inner">
    <h3 class="toc-title">Contents</h3>
    <ul class="toc-list" id="toc-list"></ul>
  </div>
</nav>
''';
  }

  String _metadataCard(Map<String, Object?> metadata, bool include, String shortId) {
    if (!include || metadata.isEmpty) return '';
    final rows = <String>[];
    for (final entry in metadata.entries) {
      if (entry.key == 'visualPages') continue;
      final value = _metadataValue(entry.value);
      if (value.isEmpty) continue;
      rows.add(
        '<div class="meta-row">'
        '<span class="meta-key">${_escapeHtml(entry.key)}</span>'
        '<span class="meta-value">${_escapeHtml(value)}</span>'
        '</div>',
      );
    }
    if (rows.isEmpty) return '';
    return '''
<div class="doc-metadata" id="document-metadata">
  <h3 class="metadata-title">Document details</h3>
  <div class="meta-grid">${rows.join()}</div>
</div>
''';
  }

  String _metadataValue(Object? value) {
    if (value == null) return '';
    if (value is String || value is num || value is bool) return '$value';
    if (value is Iterable) return value.map(_metadataValue).join(', ');
    if (value is Map) {
      return value.entries
          .map((e) => '${e.key}: ${_metadataValue(e.value)}')
          .join('; ');
    }
    return '$value';
  }

  String _visualBlock(String svg, VisualDocument? visual) {
    if (visual == null || visual.isEmpty || svg.isEmpty) return '';
    final pages = <String>[];
    var index = 0;
    for (final page in visual.pages) {
      index++;
      final pageSvg = const SvgVisualRenderer().render(VisualDocument(
        sourceFormat: visual.sourceFormat,
        pages: [page],
        contentId: visual.contentId,
        metadata: visual.metadata,
      ));
      final pageLabel = page.geometry.pageIndex != null
          ? 'Page ${page.geometry.pageIndex! + 1}'
          : 'Page $index';
      pages.add(
        '<div class="visual-page-card">'
        '<div class="visual-page-head">'
        '<span class="visual-page-label">${_escapeHtml(pageLabel)}</span>'
        '<span class="visual-page-size">${page.geometry.width.toInt()}×${page.geometry.height.toInt()}</span>'
        '</div>'
        '$pageSvg'
        '</div>',
      );
    }
    return '''
<section class="panthalassa-visuals" aria-label="Visual pages">
  <h2 class="visuals-title">Visual pages</h2>
  <div class="visual-grid">${pages.join()}</div>
</section>
''';
  }

  String _escapeHtml(String value) => value
      .replaceAll('&', '&amp;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;')
      .replaceAll('"', '&quot;')
      .replaceAll("'", '&#39;');

