  /// Client-side behavior: theme, copy, table of contents, print, back-to-top.
  static const _pageScript = r'''
(() => {
  "use strict";

  const THEME_KEY = 'panthalassa-theme';
  const html = document.documentElement;
  const themeToggle = document.getElementById('theme-toggle');
  const themeIcon = document.querySelector('.theme-icon');
  const copyBtn = document.getElementById('copy-id');
  const printBtn = document.getElementById('print-btn');
  const btt = document.getElementById('back-to-top');
  const docIdValue = document.querySelector('.doc-id-value');
  const fullId = docIdValue ? docIdValue.title : '';

  const THEME_LABELS = { light: '☀️', dark: '🌙', system: '🌓' };

  function applyTheme() {
    const stored = localStorage.getItem(THEME_KEY);
    let theme = stored || 'system';
    if (!['light', 'dark', 'system'].includes(theme)) theme = 'system';
    if (theme === 'system') {
      theme = window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
    }
    html.setAttribute('data-theme', theme);
    if (themeIcon) themeIcon.textContent = THEME_LABELS[theme] ?? '🌓';
    if (themeToggle) themeToggle.title = 'Theme: ' + theme;
  }

  function cycleTheme() {
    const order = ['light', 'dark', 'system'];
    let cur = html.getAttribute('data-theme') || 'system';
    if (!order.includes(cur)) cur = 'system';
    const next = order[(order.indexOf(cur) + 1) % order.length];
    localStorage.setItem(THEME_KEY, next);
    applyTheme();
  }

  if (themeToggle) themeToggle.addEventListener('click', cycleTheme);
  if (copyBtn && docIdValue) {
    copyBtn.addEventListener('click', async () => {
      try {
        await navigator.clipboard.writeText(fullId);
        const orig = copyBtn.innerHTML;
        copyBtn.innerHTML = '✅ Copied';
        copyBtn.classList.add('copied');
        setTimeout(() => {
          copyBtn.innerHTML = orig;
          copyBtn.classList.remove('copied');
        }, 1400);
      } catch (err) {
        // Clipboard unavailable; fall back to selection.
        docIdValue.select ? docIdValue.select() : null;
      }
    });
  }
  if (printBtn) printBtn.addEventListener('click', () => window.print());

  // Table of contents from headings within #content.
  const tocList = document.getElementById('toc-list');
  const content = document.getElementById('content');
  if (tocList && content) {
    const headings = content.querySelectorAll('h1, h2, h3, h4, h5, h6');
    const frag = document.createDocumentFragment();
    let stack = [frag];
    let levels = [0];
    headings.forEach((h) => {
      const level = Number(h.tagName.charAt(1));
      const id = h.id || ('heading-' + Math.random().toString(36).slice(2, 9));
      if (!h.id) h.id = id;
      const li = document.createElement('li');
      const a = document.createElement('a');
      a.textContent = h.textContent.trim();
      a.href = '#' + id;
      a.addEventListener('click', () => {
        document.getElementById(id)?.scrollIntoView({ behavior: 'smooth', block: 'start' });
      });
      li.appendChild(a);
      while (levels.length > 1 && level <= levels[levels.length - 1]) {
        levels.pop();
        stack.pop();
      }
      if (level > levels[levels.length - 1]) {
        const ul = document.createElement('ul');
        stack[stack.length - 1].appendChild(ul);
        stack.push(ul);
        levels.push(level);
      }
      stack[stack.length - 1].appendChild(li);
    });
    tocList.appendChild(frag);
  }

  // Active TOC item on scroll.
  const observerOpts = { root: null, rootMargin: '-20% 0% -65% 0%', threshold: 0 };
  if (tocList && content && 'IntersectionObserver' in window) {
    const observer = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        const anchor = tocList.querySelector('a[href="#' + entry.target.id + '"]');
        tocList.querySelectorAll('a.toc-active').forEach((a) => a.classList.remove('toc-active'));
        if (anchor && entry.isIntersecting) anchor.classList.add('toc-active');
      });
    }, observerOpts);
    content.querySelectorAll('h1[id], h2[id], h3[id], h4[id], h5[id], h6[id]').forEach((h) => observer.observe(h));
  }

  // Syntax-highlight JSON code blocks crudely but safely.
  function highlightJson(text) {
    return text
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"(?:\\.|[^"\\])*"\s*:/g, (m) => '<span class="json-key">' + m.replace(/\s*:$/, '') + '</span> :')
      .replace(/"(?:\\.|[^"\\])*"/g, '<span class="json-string">$&</span>')
      .replace(/\b(true|false|null)\b/g, '<span class="json-literal">$&</span>')
      .replace(/\b-?\d+\.?\d*\b/g, '<span class="json-number">$&</span>')
      .replace(/[{}[\],:]/g, '<span class="json-punct">$&</span>');
  }

  document.querySelectorAll('pre code').forEach((block) => {
    const pre = block.parentElement;
    if (!pre) return;
    const text = block.textContent || block.innerText || '';
    const trimmed = text.trim();
    let htmlContent = block.innerHTML;
    if ((trimmed.startsWith('{') || trimmed.startsWith('[')) && trimmed.length > 2) {
      try {
        htmlContent = highlightJson(text);
      } catch (e) { /* keep original */ }
    }
    block.innerHTML = htmlContent;
    pre.classList.add('has-copy');
    if (!pre.querySelector('.copy-btn')) {
      const btn = document.createElement('button');
      btn.type = 'button';
      btn.className = 'copy-btn';
      btn.textContent = 'Copy';
      btn.setAttribute('aria-label', 'Copy code');
      btn.addEventListener('click', async () => {
        try {
          await navigator.clipboard.writeText(text);
          const orig = btn.textContent;
          btn.textContent = 'Copied';
          btn.classList.add('copied');
          setTimeout(() => { btn.textContent = orig; btn.classList.remove('copied'); }, 1400);
        } catch (err) { /* noop */ }
      });
      pre.insertBefore(btn, pre.firstChild);
    }
  });

  // Back to top visibility.
  if (btt) {
    const toggleBtt = () => {
      const show = window.scrollY > 300;
      btt.classList.toggle('visible', show);
      btt.style.visibility = show ? 'visible' : 'hidden';
    };
    btt.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));
    window.addEventListener('scroll', toggleBtt, { passive: true });
    toggleBtt();
  }

  applyTheme();
})();
''';
}
